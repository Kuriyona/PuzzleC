export const DEFAULT_LOCALE: LocaleId = 'zh-Hans'

/** 语言选择项；名称用各语言的自称，任何界面语言下都显示同一组标签 */
export const LOCALE_OPTIONS = [
  { id: 'zh-Hans', label: '简体中文' },
  { id: 'zh-Hant', label: '繁體中文' },
  { id: 'en', label: 'English' },
  { id: 'ja', label: '日本語' },
] as const satisfies readonly { id: LocaleId; label: string }[]

export const LOCALE_IDS = LOCALE_OPTIONS.map((o) => o.id)

/** `<html lang>` 取值：与 LocaleId 一一对应 */
export const LOCALE_TAGS: Record<LocaleId, string> = {
  'zh-Hans': 'zh-Hans',
  'zh-Hant': 'zh-Hant',
  en: 'en',
  ja: 'ja',
}

/**
 * 取词：未知语言回落到 zh-Hans，未知键返回键名本身（不抛异常）。
 * `{name}` 占位符由 `params` 替换，缺失的占位符原样保留。
 */
export function translate(
  locale: LocaleId,
  key: MessageKey,
  params?: Record<string, string | number>,
): string {
  const template =
    MESSAGES[locale]?.[key] ?? MESSAGES[DEFAULT_LOCALE][key] ?? (key as unknown as string)
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  )
}

export function isLocaleId(value: unknown): value is LocaleId {
  return typeof value === 'string' && (LOCALE_IDS as readonly string[]).includes(value)
}
